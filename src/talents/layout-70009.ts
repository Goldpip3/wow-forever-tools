/**
 * Talents that changed name but not place in the rules, so a point in the old one lands in
 * the new. Each pair was checked against the new text: the same effect under a new name.
 */
export const RENAMED_AT_70425: Record<string, string> = {
  'Hot Streak': 'Heating Up',
  'Predatory Instincts': 'Natural Instinct',
  'Soul Harvesting': 'Soul Harvest',
  'Wake of Fire': 'Improved Fire Blast',
  'Improved Fire Nova': 'Trial by Fire',
};

const built = new Map<string, ClassTalents>();

/** The old trees for one class, keyed the way the talent data is ('Warrior'), or null. */
export function layoutBefore70425(dataKey: string): ClassTalents | null {
  const rows = LAYOUT[dataKey];
  if (!rows) return null;
  let cls = built.get(dataKey);
  if (!cls) {
    cls = {
      icon: '',
      trees: rows.map(([name, talents]) => ({
        name,
        bg: 0,
        icon: '',
        talents: talents.map(([talentName, max, row, col, req]): Talent => ({
          name: talentName, max, row, col, icon: '', desc: [], ...(req ? { req } : {}),
        })),
      })),
    };
    built.set(dataKey, cls);
  }
  return cls;
}
